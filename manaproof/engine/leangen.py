"""Lean code generation and the bridge to the Lean kernel.

`write_cards` renders the Python card pool as `Manaproof/Cards.lean`, so both
interpreters read the same programs.  `verify` renders a certificate as a
Lean file and asks Lean to check it.
"""
import glob, os, shutil, subprocess, tempfile, time
from .model import ACC_NAMES

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEAN_DIR = os.path.join(ROOT, "lean")
OLEAN_DIR = os.path.join(LEAN_DIR, ".lake", "build", "lib", "lean")
K_BOUNDED = 6    # iterations checked for grade-B certificates


def b(x): return "true" if x else "false"
def opt(i): return "none" if i is None or i < 0 else f"some {i}"
def lst(xs): return "[" + ", ".join(xs) + "]"


def acc(a):
    parts = [f"{n} := {v}" for n, v in zip(ACC_NAMES, a) if v]
    return "{ " + ", ".join(parts) + " }" if parts else "{}"


def filt(f):
    parts = []
    if f.all: parts.append(f"all := {list(f.all)}")
    if f.no: parts.append(f"no := {list(f.no)}")
    if f.color >= 0: parts.append(f"color := some {f.color}")
    if f.nontoken: parts.append("nontoken := true")
    if f.other: parts.append("other := true")
    return "{ " + ", ".join(parts) + " }" if parts else "{}"


def effect(e):
    k = e[0]
    if k == "gain": return f".gain {acc(e[1])}"
    if k == "gainCtx": return f".gainCtx {b(e[1])}"
    if k == "addAny": return f".addAny {e[1]}"
    if k == "addPer": return f".addPer {filt(e[1])} {e[2]}"
    if k in ("addPerColor", "untapSelf"): return "." + k
    if k in ("untapTarget", "untapAll", "copyTarget", "blink", "lifelink"): return f".{k} {filt(e[1])}"
    if k == "token": return f".token {e[1]} {e[2]}"
    if k in ("ctrSelf", "ping"): return f".{k} {e[1]}"
    if k in ("ctrTarget", "ctrAll"): return f".{k} {filt(e[1])} {e[2]}"
    if k == "ret": return f".ret .{e[1]}"
    raise ValueError(k)


def cost(c):
    parts = []
    if c.tap: parts.append("tap := true")
    if c.untap: parts.append("untap := true")
    if any(c.mana): parts.append(f"mana := {acc(c.mana)}")
    if c.generic: parts.append(f"generic := {c.generic}")
    if c.sac[0] == "self": parts.append("sac := .self")
    elif c.sac[0] == "other": parts.append(f"sac := .other {filt(c.sac[1])}")
    if c.tapOther is not None: parts.append(f"tapOther := some {filt(c.tapOther)}")
    if c.removeCtr: parts.append(f"removeCtr := {c.removeCtr}")
    if c.putNeg: parts.append(f"putNeg := {c.putNeg}")
    if c.life: parts.append(f"life := {c.life}")
    if c.loyal: parts.append("loyal := true")
    return "{ " + ", ".join(parts) + " }" if parts else "{}"


def on(o):
    return f".{o[0]} {filt(o[1])}" if len(o) > 1 else "." + o[0]


def ability(a):
    if a[0] == "act": return f".act {cost(a[1])} {lst(effect(e) for e in a[2])}"
    if a[0] == "trig": return f".trig ({on(a[1])}) {b(a[2])} {a[3]} {lst(effect(e) for e in a[4])}"
    if a[0] == "kw": return f".kw .{a[1]}"
    return f".tough {a[1]}"


def card(c):
    parts = [f'name := "{c.name}"', f"tags := {list(c.tags)}"]
    if c.colors: parts.append(f"colors := {list(c.colors)}")
    if c.tough: parts.append(f"tough := {c.tough}")
    if c.abilities: parts.append("abilities := " + lst(ability(a) for a in c.abilities))
    if c.grants:
        gs = [f"⟨{'.attached' if s[0] == 'attached' else '.all ' + filt(s[1])}, {ability(a)}⟩" for s, a in c.grants]
        parts.append("grants := " + lst(gs))
    for k in ("enterCtr", "setupCtr", "reduceHost"):
        if getattr(c, k): parts.append(f"{k} := {getattr(c, k)}")
    for k in ("negReduce", "noNeg", "bonusC", "entersTapped"):
        if getattr(c, k): parts.append(f"{k} := true")
    if c.enchant is not None: parts.append(f"enchant := some {filt(c.enchant)}")
    return "{ " + ",\n    ".join(parts) + " }"


def cards_source(db):
    body = ",\n".join(f"  -- {i}\n  {card(c)}" for i, c in enumerate(db))
    return ("/- GENERATED by engine/leangen.py from engine/pool.py — do not edit. -/\n"
            "import Manaproof.Model\nnamespace Manaproof.Cards\n\n"
            f"def db : List Card := [\n{body}\n]\n\nend Manaproof.Cards\n")


def write_cards(db):
    path = os.path.join(LEAN_DIR, "Manaproof", "Cards.lean")
    src = cards_source(db)
    if not os.path.exists(path) or open(path).read() != src:
        open(path, "w").write(src)
        return True
    return False


def action(a):
    if a[0] == "act": return f".act {a[1]} {a[2]} {acc(a[3])} {a[4]} {a[5]} {a[6]}"
    if a[0] == "resolve": return f".resolve {acc(a[1])} {a[2]} {a[3]}"
    return ".skip"


def cert_source(cert, native=False):
    """cert: dict with cards [(idx, att)], float, pre, loop, grade, delta, summary."""
    tac = "native_decide" if native else "decide +kernel"
    cards = lst(f"({k}, {opt(a)})" for k, a in cert["cards"])
    names = " + ".join(cert["names"])
    out = [f"/- Certificate {cert['id']}: {names}",
           f"   claim: {cert['claim']}   (grade {cert['grade']}) -/",
           "import Manaproof", "open Manaproof", "",
           "def cert : Cert := {",
           f"  cards := {cards},",
           f"  float := {acc(cert['float'])},",
           f"  pre := {lst(action(a) for a in cert['pre'])},",
           f"  loop := {lst(action(a) for a in cert['loop'])} }}", ""]
    if cert["grade"] == "A":
        out += ["/-- The kernel re-executes the trace: the loop returns to the same board, richer. -/",
                f"theorem cert_ok : checkA Cards.db cert = true := by {tac}", "",
                "/-- Net yield of one iteration. -/",
                f"theorem cert_delta : loopDelta Cards.db cert = some {acc(cert['delta'])} := by {tac}", "",
                "/-- Therefore the loop can be iterated any number of times. -/",
                "theorem cert_unbounded :",
                "    ∃ (s : State) (δ : Acc), δ ≠ Acc.zero ∧ run Cards.db (cert.init Cards.db) cert.pre = some s ∧",
                "      ∀ n, run Cards.db (cert.init Cards.db) (cert.pre ++ rep n cert.loop)",
                "        = some ⟨s.cfg, s.acc.add (Acc.smul n δ)⟩ :=",
                "  checkA_sound Cards.db cert cert_ok"]
    else:
        n, a = cert["summary"]
        out += [f"/-- The kernel re-executes {K_BOUNDED} consecutive iterations; each strictly grows the board. -/",
                f"theorem cert_ok : checkB Cards.db cert {K_BOUNDED} = true := by {tac}", "",
                f"/-- Board size and resources after {K_BOUNDED} iterations. -/",
                f"theorem cert_summary : summary Cards.db cert {K_BOUNDED} = some ({n}, {acc(a)}) := by {tac}"]
    return "\n".join(out) + "\n"


_lean = None


def find_lean():
    global _lean
    if _lean is not None: return _lean or None
    cands = [os.environ.get("MANAPROOF_LEAN"), shutil.which("lean"),
             os.path.expanduser("~/.elan/bin/lean")] + sorted(glob.glob("/opt/lean/*/bin/lean"))
    for c in cands:
        if c and os.path.exists(c):
            _lean = c
            return c
    _lean = ""
    return None


def lean_version():
    lean = find_lean()
    if not lean: return None
    try:
        return subprocess.run([lean, "--version"], capture_output=True, text=True, timeout=20).stdout.strip()
    except Exception:
        return None


def build_kernel():
    """Compile the kernel library (lake build). Returns (ok, log)."""
    lean = find_lean()
    if not lean: return False, "Lean toolchain not found (set MANAPROOF_LEAN or install elan)."
    lake = os.path.join(os.path.dirname(lean), "lake")
    env = dict(os.environ, PATH=os.path.dirname(lean) + os.pathsep + os.environ.get("PATH", ""))
    r = subprocess.run([lake, "build"], cwd=LEAN_DIR, capture_output=True, text=True, env=env, timeout=900)
    return r.returncode == 0, (r.stdout + r.stderr).strip()


def verify(cert, timeout=120):
    """Returns dict(status=verified|rejected|unavailable, tactic, seconds, log, source)."""
    src = cert_source(cert)
    lean = find_lean()
    if not lean or not os.path.isdir(OLEAN_DIR):
        return {"status": "unavailable", "log": "Lean kernel not built.", "source": src, "seconds": 0, "tactic": ""}
    env = dict(os.environ, LEAN_PATH=OLEAN_DIR)
    t0 = time.time()
    for native in (False, True):
        s = cert_source(cert, native)
        with tempfile.NamedTemporaryFile("w", suffix=".lean", delete=False) as f:
            f.write(s); path = f.name
        try:
            r = subprocess.run([lean, path], capture_output=True, text=True, env=env, timeout=timeout)
            log = (r.stdout + r.stderr).replace(path, "cert.lean").strip()
            ok = r.returncode == 0
        except subprocess.TimeoutExpired:
            ok, log = False, "timeout"
        finally:
            os.unlink(path)
        if ok:
            return {"status": "verified", "tactic": "native_decide" if native else "decide +kernel",
                    "seconds": round(time.time() - t0, 2), "log": log, "source": s}
        # only retry natively when kernel reduction ran out of budget, not on a real mismatch
        if "maximum recursion depth" not in log and "timeout" not in log and "deterministic" not in log:
            break
    return {"status": "rejected", "tactic": "", "seconds": round(time.time() - t0, 2), "log": log, "source": src}
